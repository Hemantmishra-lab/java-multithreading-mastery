package core.java.concurrency;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.Callable;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;

/**
 * Demonstrates using ExecutorService to manage a pool of worker threads
 * and concurrently execute both Runnable and Callable tasks.
 */
public class Executor_Service_Demo {

    public static void main(String[] args) {
        System.out.println("=== ExecutorService Thread Pool Demo ===\n");

        // 1. Create a Fixed Thread Pool with 3 reusable worker threads
        ExecutorService executorService = Executors.newFixedThreadPool(3);

        try {
            // 2. Submit Runnable tasks (fire-and-forget tasks)
            for (int i = 1; i <= 3; i++) {
                executorService.execute(new OrderProcessingRunnable("ORD-10" + i));
            }

            // 3. Submit multiple Callable tasks and collect their Futures
            List<Future<String>> reportFutures = new ArrayList<>();
            for (int i = 1; i <= 4; i++) {
                Callable<String> task = new ReportGeneratorCallable("Report-" + i);
                reportFutures.add(executorService.submit(task));
            }

            // 4. Retrieve results from all Futures
            System.out.println("\n--- Collecting Callable Results ---");
            for (Future<String> future : reportFutures) {
                System.out.println("Completed: " + future.get());
            }

        } catch (InterruptedException | ExecutionException e) {
            System.err.println("Error executing tasks: " + e.getMessage());
            Thread.currentThread().interrupt();
        } finally {
            // 5. Gracefully shut down the ExecutorService
            shutdownExecutor(executorService);
        }
    }

    private static void shutdownExecutor(ExecutorService executor) {
        System.out.println("\nInitiating graceful shutdown...");
        executor.shutdown();
        try {
            if (!executor.awaitTermination(5, TimeUnit.SECONDS)) {
                executor.shutdownNow();
            }
            System.out.println("ExecutorService terminated cleanly.");
        } catch (InterruptedException e) {
            executor.shutdownNow();
            Thread.currentThread().interrupt();
        }
    }
}

class OrderProcessingRunnable implements Runnable {
    private final String orderId;

    public OrderProcessingRunnable(String orderId) {
        this.orderId = orderId;
    }

    @Override
    public void run() {
        System.out.println(Thread.currentThread().getName() + " processing order: " + orderId);
        try {
            Thread.sleep(300);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
    }
}

class ReportGeneratorCallable implements Callable<String> {
    private final String reportName;

    public ReportGeneratorCallable(String reportName) {
        this.reportName = reportName;
    }

    @Override
    public String call() throws Exception {
        System.out.println(Thread.currentThread().getName() + " generating " + reportName);
        Thread.sleep(400);
        return reportName + " [Generated by " + Thread.currentThread().getName() + "]";
    }
}